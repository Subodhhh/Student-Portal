#!/usr/bin/env python3
"""Generate backend/institute-gateway/nginx.conf from the services' own route definitions (same table the tests use).

    python scripts/gen_gateway_conf.py            # (re)write the file
    python scripts/gen_gateway_conf.py --check    # exit 1 if the committed file is stale
Needs the service packages importable (see backend/institute-integration-tests/tests/conftest.py for the paths)."""
import glob
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
for d in glob.glob(f"{ROOT}/backend/institute-*-service") + [f"{ROOT}/backend/institute-common"]:
    sys.path.insert(0, d)
os.environ.setdefault("DATABASE_URL", "sqlite://")
os.environ.setdefault("CORS_ORIGINS", "http://localhost")

from institute_common.gateway import ambiguities, route_table  # noqa: E402

from inst_academics.main import app as academics  # noqa: E402
from inst_enrollment.main import app as enrollment  # noqa: E402
from inst_exam.main import app as exam  # noqa: E402
from inst_identity.main import app as identity  # noqa: E402
from inst_operations.main import app as operations  # noqa: E402
from inst_organization.main import app as organization  # noqa: E402
from inst_paper.main import app as paper  # noqa: E402

SERVICES = {"identity": identity, "organization": organization, "academics": academics, "enrollment": enrollment,
            "paper": paper, "exam": exam, "operations": operations}
OUT = f"{ROOT}/backend/institute-gateway/nginx.conf"


def render() -> str:
    table = route_table(SERVICES)
    bad = ambiguities(table)
    if bad:
        sys.exit("ambiguous routes:\n" + "\n".join(bad))
    entries = sorted({(e.path, e.service) for e in table}, key=lambda x: (-sum(1 for s in x[0].split("/") if s and not s.startswith("{")), x[0]))
    out = ["# GENERATED by scripts/gen_gateway_conf.py from the services' route definitions. Do not edit by hand.",
           "# One public origin for the Institute UI: the browser keeps talking to a single host (cookies, CORS, CSRF unchanged).", ""]
    out += ["server {", "    listen 80;", "    server_name _;", "    client_max_body_size 3m;   # paper uploads are limited to 2 MB by the paper service", "",
            "    # Upstreams are resolved through Docker's embedded DNS at request time (not once at start-up), so a restarted or",
            "    # recreated service with a new IP is reached again within `valid` seconds instead of answering 502 until nginx restarts.",
            "    resolver 127.0.0.11 valid=10s ipv6=off;",
            "    resolver_timeout 3s;"]
    out += [f"    set $institute_{svc} institute-{svc}-service:8000;" for svc in SERVICES]
    out += ["",
            "    proxy_set_header Host $host;", "    proxy_set_header X-Real-IP $remote_addr;", "    proxy_set_header X-Forwarded-For $remote_addr;",
            "    proxy_set_header X-Forwarded-Proto $scheme;", "    proxy_connect_timeout 3s;", "    proxy_read_timeout 30s;", "",
            "    add_header X-Content-Type-Options nosniff always;", "    add_header X-Frame-Options DENY always;", "",
            "    location = /health { default_type application/json; return 200 '{\"status\":\"ok\",\"service\":\"institute-gateway\"}'; }",
            "    # Service-to-service APIs are never reachable from outside.",
            "    location ^~ /internal/ { return 404; }", ""]
    for path, svc in entries:
        regex = "^" + re.sub(r"\\\{[^/]+?\\\}", "[^/]+", re.escape(path)).replace("\\/", "/") + "$"
        out.append(f"    location ~ {regex} {{ proxy_pass http://$institute_{svc}; }}")
    out += ["", "    location / { default_type application/json; return 404 '{\"detail\":{\"code\":\"NOT_FOUND\",\"message\":\"No such route.\"}}'; }", "}", ""]
    return "\n".join(out)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        current = open(OUT).read() if os.path.exists(OUT) else ""
        if current != text:
            sys.exit("backend/institute-gateway/nginx.conf is stale: run python scripts/gen_gateway_conf.py")
        print("gateway configuration is up to date")
    else:
        open(OUT, "w").write(text)
        print(f"wrote {OUT} ({text.count('location ~')} routes)")

"""Generation of a centrally scheduled Global Test occurrence from the providers' paper submissions: ONE unified exam per student.

At the submission deadline (start - test.generate_lead_minutes) the worker resolves, per provider, which student each ACTIVE
submission covers (its audience, resolved from CURRENT enrollments with the Create Test rule), then combines the providers per student:

  * within one provider, a student covered by two submissions of the same subject is AMBIGUOUS: neither paper for that subject and
    the provider is told (never a silent choice of one teacher's paper);
  * across providers, a student covered for the same subject by papers of two providers is a CONFLICT: neither paper for that
    subject, every provider involved is told, and the student's other subjects are generated as usual (never a choice of provider);
  * a paper version that is not APPROVED/PUBLISHED by the deadline is not used (missing; the provider is told);
  * a provider that offers a subject of the test but submitted no usable paper for it is told; no other provider's or teacher's paper is
    ever used instead;
  * students with the same COMBINED set of papers (each subject's paper from its own provider's submission) form one group, and each
    group becomes ONE ordinary exam plan (audience: those students, slots: those exact paper versions with their submissions, marking
    and duration of the test), generated by the normal generator. So every student has exactly one exam, one card, one attempt and
    one shared timer for the occurrence, and delivery, attempts, evaluation and results are the existing ones. Who on the provider
    side may see what of such an exam is decided by services/unified.py (their own subjects and students only).

Idempotent: a group's plan is keyed by (occurrence, combined paper set) through exam_plans.client_request_id and the generator is
idempotent per plan, so a retried or concurrent run creates nothing twice; the occurrence is marked generated only when every group
succeeded. Generated exams never change afterwards (late submissions are refused at the deadline). Occurrences generated before
unified generation keep their per-provider exams unchanged (an occurrence is generated only once)."""
import hashlib
from collections import defaultdict
from datetime import datetime, timedelta
from uuid import UUID

from sqlalchemy import select
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from institute_common.core import audit

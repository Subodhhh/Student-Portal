READY = {"APPROVED", "PUBLISHED"}
MAX_ATTEMPTS = 3          # generation attempts of one unified group before it stops holding the occurrence back


def deadline(test: GlobalTest, occ: GlobalTestOccurrence) -> datetime:
    """Papers are accepted (and withdrawn) until this moment; then the occurrence is generated."""
    return occ.start_at - timedelta(minutes=test.generate_lead_minutes)


def submission_class(db: Session, sub: GlobalPaperSubmission) -> tuple[str | None, str | None]:
    """The Global Test's Class for matching: (code or UNMATCHABLE, problem). A legacy label is never guessed: it reaches nobody through
    batches (staff-listed students still count) and the occurrence report names the problem."""
    test = db.get(GlobalTest, db.get(GlobalTestOccurrence, sub.occurrence_id).test_id)
    code, problem = class_target(test.target_class)
    return (gen.UNMATCHABLE if problem else code), problem


_LOOKUP = object()


def resolve_submission(db: Session, sub: GlobalPaperSubmission, class_level=_LOOKUP) -> list[tuple[str, str, UUID | None]]:
    """Students one submission reaches: its audience, its one subject and (by default) its Global Test's Class."""
    from inst_exam.routes.tests import TestAudienceIn, resolve
    if class_level is _LOOKUP:
        class_level, _problem = submission_class(db, sub)
    return resolve(db, TestAudienceIn.model_validate(sub.audience), [sub.subject_id], class_level)


def assignments(db: Session, occ: GlobalTestOccurrence, provider_id: UUID) -> dict:
    """Who gets which paper for one provider: {"papers": {student: {subject: (submission, enrollment_id)}}, "ambiguous": {(student,
    subject)}, "not_ready": [submission]}. Pure computation, writes nothing (also used for coverage before the deadline)."""
    subs = db.scalars(select(GlobalPaperSubmission).where(GlobalPaperSubmission.occurrence_id == occ.occurrence_id,
                                                          GlobalPaperSubmission.provider_id == provider_id,
                                                          GlobalPaperSubmission.status == "ACTIVE")
                      .order_by(GlobalPaperSubmission.submitted_at)).all()
    papers: dict[str, dict[UUID, tuple[GlobalPaperSubmission, str]]] = defaultdict(dict)
    ambiguous: set[tuple[str, UUID]] = set()
    not_ready = []
    code, problem = class_target(db.get(GlobalTest, occ.test_id).target_class)    # one Class for the whole occurrence
    class_level = gen.UNMATCHABLE if problem else code
    for sub in subs:
        v = db.get(PaperVersion, sub.paper_version_id)
        if not v or v.status not in READY:
            not_ready.append(sub)
            continue
        for sid, eid, _bid in resolve_submission(db, sub, class_level):
            if sub.subject_id in papers[sid] and papers[sid][sub.subject_id][0].submission_id != sub.submission_id:
                ambiguous.add((sid, sub.subject_id))
            else:
                papers[sid][sub.subject_id] = (sub, eid)
    for sid, subject in ambiguous:
        papers[sid].pop(subject, None)
    return {"papers": {sid: m for sid, m in papers.items() if m}, "ambiguous": ambiguous, "not_ready": not_ready}


def _provider_admins(db: Session, provider_id: UUID) -> list[UUID]:
    return list(db.scalars(select(StaffRoleAssignment.staff_id).where(StaffRoleAssignment.provider_id == provider_id,
                                                                      StaffRoleAssignment.role == Role.PROVIDER_ADMIN.value,
                                                                      StaffRoleAssignment.status == "ACTIVE")))


def _uncovered(db: Session, provider_id: UUID, covered: set[str]) -> dict[str, int]:
    """Active students of the provider that no submission covers, counted per branch name (who did not get the test at all)."""
    from institute_common.models.org import Branch, Enrollment
    out: dict[str, int] = defaultdict(int)
    seen = set()
    for sid, branch in db.execute(select(Enrollment.student_id, Branch.name).join(Branch, Branch.branch_id == Enrollment.branch_id)
                                  .where(Enrollment.provider_id == provider_id, Enrollment.status == "ACTIVE")):
        if sid not in covered and sid not in seen:
            seen.add(sid)
            out[branch] += 1
    return dict(out)


def merge(per_provider: dict[UUID, dict]) -> tuple[dict[str, dict[UUID, tuple[GlobalPaperSubmission, str]]], dict[tuple[str, UUID], set[UUID]]]:
    """Combine every provider's assignments into one paper per student and subject. A subject covered for one student by papers of
    two providers is a CONFLICT: the student gets neither paper for it and both providers are told (never a choice)."""
    claims: dict[tuple[str, UUID], list[tuple[GlobalPaperSubmission, str]]] = defaultdict(list)
    for a in per_provider.values():
        for sid, per in a["papers"].items():
            for subject, pick in per.items():
                claims[(sid, subject)].append(pick)
    merged: dict[str, dict[UUID, tuple[GlobalPaperSubmission, str]]] = defaultdict(dict)
    conflicts: dict[tuple[str, UUID], set[UUID]] = {}
    for (sid, subject), picks in claims.items():
        if len(picks) > 1:
            conflicts[(sid, subject)] = {sub.provider_id for sub, _eid in picks}
        else:
            merged[sid][subject] = picks[0]
    return {sid: m for sid, m in merged.items() if m}, conflicts


def _group_key(occ: GlobalTestOccurrence, paper_set: tuple) -> str:
    """Unified plans: one per (occurrence, combined paper set); the gocc2 prefix never meets the older per-provider gocc keys."""
    digest = hashlib.sha256(repr(paper_set).encode()).hexdigest()[:32]
    return f"gocc2:{occ.occurrence_id.hex}:{digest}"


def _plan_for_group(db: Session, test: GlobalTest, occ: GlobalTestOccurrence, subject_order: list[UUID],
                    picks: dict[UUID, GlobalPaperSubmission], students: list[str]) -> ExamPlan:
    """One unified plan: the students sharing exactly this combined paper set, each subject from its own submission. The provider and
    branch columns hold the first subject's submission only as an anchor (services/unified.py: they grant nothing)."""
    ordered = [s for s in subject_order if s in picks]
    base = _group_key(occ, tuple((s, picks[s].submission_id) for s in ordered))
    existing = db.scalars(select(ExamPlan).where((ExamPlan.client_request_id == base) | ExamPlan.client_request_id.like(base + ":%"))
                          .order_by(ExamPlan.created_at)).all()
    for plan in existing:
        if not db.scalar(select(Exam.exam_id).where(Exam.plan_id == plan.plan_id).limit(1)):
            # not generated yet (an earlier attempt failed): its audience follows the CURRENT resolution
            have = set(db.scalars(select(ExamPlanStudent.student_id).where(ExamPlanStudent.plan_id == plan.plan_id)))
            for row in db.scalars(select(ExamPlanStudent).where(ExamPlanStudent.plan_id == plan.plan_id, ExamPlanStudent.student_id.not_in(students))):
                db.delete(row)
            for sid in set(students) - have:
                db.add(ExamPlanStudent(plan_id=plan.plan_id, student_id=sid))
            db.commit()
            return plan
    # the same paper set was generated already: these students (none holds this date yet) get a follow-up plan, never nothing
    key = base if not existing else f"{base}:{len(existing)}"
    plan = db.scalar(select(ExamPlan).where(ExamPlan.client_request_id == key))
    if plan:
        return plan
    anchor = picks[ordered[0]]
    plan = ExamPlan(provider_id=anchor.provider_id, branch_id=anchor.branch_id, name=test.name, description=test.description,
                    duration_minutes=test.duration_minutes, start_at=occ.start_at, end_at=occ.end_at, auto_publish=True, status="ACTIVE",
                    audience_type="STUDENTS", marking_mode=test.marking_mode, marks_correct=test.marks_correct, marks_wrong=test.marks_wrong,
                    exam_type=test.exam_type, target_class=test.target_class, global_test_id=test.test_id,
                    global_occurrence_id=occ.occurrence_id, client_request_id=key, created_by=test.created_by)
    db.add(plan)
    try:
        db.flush()
        for sid in students:
            db.add(ExamPlanStudent(plan_id=plan.plan_id, student_id=sid))
        for pos, subject in enumerate(ordered, start=1):
            db.add(ExamPlanSubject(plan_id=plan.plan_id, position=pos, subject_id=subject, paper_version_id=picks[subject].paper_version_id,
                                   source_submission_id=picks[subject].submission_id))
        db.commit()
    except IntegrityError:          # a concurrent run created this group's plan first
        db.rollback()
        plan = db.scalar(select(ExamPlan).where(ExamPlan.client_request_id == key))
    return plan


def _given_up(db: Session, plan: ExamPlan) -> ExamGenerationJob | None:
    """The plan's run for its window if it already failed MAX_ATTEMPTS times: it is not tried again."""
    job = db.scalar(select(ExamGenerationJob).where(ExamGenerationJob.plan_id == plan.plan_id,
                                                    ExamGenerationJob.run_key == gen.canonical_run_key(plan.start_at)))
    return job if job and job.status == "FAILED" and job.attempts >= MAX_ATTEMPTS else None


def _notify_abandoned(db: Session, test: GlobalTest, occ: GlobalTestOccurrence, plan: ExamPlan, students: list[str],
                      providers: set[UUID], error: str | None, when: str) -> None:
    """A unified group whose generation failed MAX_ATTEMPTS times: its students have NO exam for the date. The platform (which owns
    the plan) is told the cause; each contributing provider's admins are told how many of their students are affected, nothing about
    any other provider. Idempotent per plan."""
    from inst_exam.routes.global_contributions import _platform_staff
    n = len(students)
    notify(db, _platform_staff(db), kind="GLOBAL_TEST_GENERATION_FAILED", title=f"{test.name} ({when}): {n} student(s) got no exam",
           body=f"Generating one group of this Global Test date failed {MAX_ATTEMPTS} times and was stopped, so {n} student(s) have no exam "
                f"for it. Last error: {(error or 'unknown')[:300]}\nPlan: {plan.plan_id}", dedupe=f"gabandon:{plan.plan_id}")
    for provider_id in sorted(providers, key=str):
        notify(db, _provider_admins(db, provider_id), kind="GLOBAL_TEST_GENERATION_FAILED", title=f"{test.name} ({when}): exam not generated",
               body=f"{n} of your students could not be given this Global Test date because its generation failed. The platform has been told.",
               dedupe=f"gabandon:{plan.plan_id}:{provider_id}", provider_id=provider_id)


def generate_occurrence(db: Session, occ: GlobalTestOccurrence, now: datetime | None = None) -> dict:
    """Generate one unified exam per student for one occurrence (see module docstring). Returns a report."""
    now = now or utcnow()
    test = db.get(GlobalTest, occ.test_id)
    subject_order = [s for (s,) in db.execute(select(GlobalTestSubject.subject_id).where(GlobalTestSubject.test_id == test.test_id)
                                              .order_by(GlobalTestSubject.position))]
    names = dict(db.execute(select(Subject.subject_id, Subject.name).where(Subject.subject_id.in_(subject_order or [None]))).all())
    providers = sorted({p for (p,) in db.execute(select(GlobalPaperSubmission.provider_id).where(
        GlobalPaperSubmission.occurrence_id == occ.occurrence_id, GlobalPaperSubmission.status == "ACTIVE"))}, key=str)
    offering = sorted({p for (p,) in db.execute(select(ProviderSubject.provider_id).where(ProviderSubject.subject_id.in_(subject_order or [None])))}, key=str)
    report = {"plans": 0, "exams": [], "students": 0, "ambiguous": 0, "conflicts": 0, "missing": [], "failed": []}
    _code, class_problem = class_target(test.target_class)
    if class_problem:
        report["class_problem"] = class_problem
    when = occ.start_at.strftime("%d %b %Y %H:%M UTC")

    per_provider: dict[UUID, dict] = {}
    for provider_id in providers:
        try:
            per_provider[provider_id] = assignments(db, occ, provider_id)
        except Exception as exc:  # noqa: BLE001  (a student's combined exam needs every provider: generate nothing, retry next pass)
            db.rollback()
            report["failed"].append({"provider_id": str(provider_id), "error": f"{type(exc).__name__}: {str(exc)[:200]}"})
    if not report["failed"]:
        papers, conflicts = merge(per_provider)
        report["conflicts"] = len(conflicts)
        holding = set(db.scalars(select(StudentExamAssignment.student_id).join(Exam, Exam.exam_id == StudentExamAssignment.exam_id)
                                 .join(ExamPlan, ExamPlan.plan_id == Exam.plan_id)
                                 .where(ExamPlan.global_occurrence_id == occ.occurrence_id, Exam.status != "CANCELLED")))
        papers = {sid: per for sid, per in papers.items() if sid not in holding}     # one exam per student per date, whatever changed since
        groups: dict[tuple, list[str]] = defaultdict(list)
        group_picks: dict[tuple, dict[UUID, GlobalPaperSubmission]] = {}
        for sid, per_subject in sorted(papers.items()):
            paper_set = tuple(sorted((subject, sub.submission_id) for subject, (sub, _eid) in per_subject.items()))
            groups[paper_set].append(sid)
            group_picks[paper_set] = {subject: sub for subject, (sub, _eid) in per_subject.items()}
        for paper_set, students in groups.items():
            try:
                plan = _plan_for_group(db, test, occ, subject_order, group_picks[paper_set], students)
                job = _given_up(db, plan) or gen.generate(db, plan.plan_id)
            except Exception as exc:  # noqa: BLE001  (recorded and retried on the next pass; the other groups continue)
                db.rollback()
                report["failed"].append({"group": len(report["exams"]), "error": f"{type(exc).__name__}: {str(exc)[:200]}"})
                continue
            if job.status == "FAILED":       # retried on the next passes; after MAX_ATTEMPTS it stays recorded but stops blocking the date
                bucket = "failed" if job.attempts < MAX_ATTEMPTS else "abandoned"
                report.setdefault(bucket, []).append({"plan_id": str(plan.plan_id), "error": (job.error or "generation failed")[:200]})
                if bucket == "abandoned":
                    _notify_abandoned(db, test, occ, plan, students, {sub.provider_id for sub in group_picks[paper_set].values()}, job.error, when)
                continue
            report["plans"] += 1
            report["students"] += len(students)
            if job.exam_id:
                report["exams"].append(str(job.exam_id))

        # what each provider is missing: tell its admins (and never fill the gap with someone else's paper)
        for provider_id, a in per_provider.items():
            mine = {(sid, subject) for (sid, subject), provs in conflicts.items() if provider_id in provs}
            kept = {sid: {s: x for s, x in per.items() if (sid, s) not in mine} for sid, per in a["papers"].items()}
            covered = {subject for per in kept.values() for subject in per}
            offered = {s for (s,) in db.execute(select(ProviderSubject.subject_id).where(ProviderSubject.provider_id == provider_id,
                                                                                       ProviderSubject.subject_id.in_(subject_order)))}
            partial = defaultdict(int)
            for per in kept.values():
                for subject in offered - set(per):
                    partial[subject] += 1
            problems = [f"{names.get(s, 'A subject')}: no usable paper was submitted" for s in offered - covered - {s for _sid, s in mine}]
            problems += [f"{names.get(s, 'A subject')}: {n} student(s) are not covered by any submission and sit the test without it"
                         for s, n in partial.items() if s in covered]
            problems += [f"A {names.get(sub.subject_id, 'subject')} paper was not approved by the deadline and was not used" for sub in a["not_ready"]]
            uncovered = _uncovered(db, provider_id, set(a["papers"]) | {sid for sid, _s in a["ambiguous"]})
            if uncovered:
                problems.append(f"{sum(uncovered.values())} active student(s) are covered by no paper and were not assigned this test "
                                f"({', '.join(f'{b}: {n}' for b, n in sorted(uncovered.items()))})")
            if a["ambiguous"]:
                problems.append(f"{len(a['ambiguous'])} student/subject pair(s) were covered by two submissions and received neither paper")
                report["ambiguous"] += len(a["ambiguous"])
            if mine:
                subjects = ", ".join(sorted({names.get(s, "a subject") for _sid, s in mine}))
                problems.append(f"{len(mine)} student/subject pair(s) ({subjects}) were also covered by another provider's paper and received "
                                f"neither paper")
            if problems:
                report["missing"].append({"provider_id": str(provider_id), "problems": problems})
                notify(db, _provider_admins(db, provider_id), kind="GLOBAL_TEST_MISSING_PAPERS", title=f"{test.name} ({when}): papers missing",
                       body="The Global Test was generated for your students with these gaps:\n- " + "\n- ".join(problems),
                       dedupe=f"gmiss:{occ.occurrence_id}:{provider_id}", provider_id=provider_id)
        # providers that offer a subject of the test and submitted nothing at all
        for provider_id in offering:
            if provider_id not in providers:
                notify(db, _provider_admins(db, provider_id), kind="GLOBAL_TEST_MISSING_PAPERS", title=f"{test.name} ({when}): no papers submitted",
                       body="No paper was submitted for this Global Test, so none of your students were assigned it.",
                       dedupe=f"gmiss:{occ.occurrence_id}:{provider_id}", provider_id=provider_id)
    occ = db.get(GlobalTestOccurrence, occ.occurrence_id)
    errors = report["failed"] + report.get("abandoned", [])
    occ.generation_error = "; ".join(f["error"] for f in errors)[:1000] or None
    if not report["failed"]:
        occ.generated_at = now
    db.commit()
    audit.record(db, "global_test.occurrence.generate", "FAILURE" if report["failed"] else "SUCCESS", service="exam-scheduler",
                 target_type="global_test_occurrence", target_id=occ.occurrence_id,
                 details={k: (v if k != "exams" else len(v)) for k, v in report.items()})
    return report


def run_due(db: Session, now: datetime | None = None) -> list[dict]:
    """Worker entry point: generate every published occurrence whose submission deadline has passed and that is not generated yet."""
    now = now or utcnow()
    out = []
    rows = db.execute(select(GlobalTestOccurrence, GlobalTest).join(GlobalTest, GlobalTest.test_id == GlobalTestOccurrence.test_id)
                      .where(GlobalTestOccurrence.status == "PUBLISHED", GlobalTestOccurrence.generated_at.is_(None),
                             GlobalTest.status == "PUBLISHED", GlobalTest.kind == "SCHEDULE")).all()
    for occ, test in rows:
        if deadline(test, occ) <= now:
            out.append({"occurrence_id": str(occ.occurrence_id), **generate_occurrence(db, occ, now)})
    return out

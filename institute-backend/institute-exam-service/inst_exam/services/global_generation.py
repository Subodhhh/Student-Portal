"""Generation of a centrally scheduled Global Test occurrence from the providers' paper submissions.

At the submission deadline (start - test.generate_lead_minutes) the worker resolves, per provider, which student each ACTIVE
submission covers (its audience, resolved from CURRENT enrollments with the Create Test rule) and gives every student exactly the paper of
the submission that covers them, per subject:

  * a student covered by two submissions of the same provider and subject is AMBIGUOUS: they get neither paper for that subject and
    the provider is told (never a silent choice of one teacher's paper);
  * a paper version that is not APPROVED/PUBLISHED by the deadline is not used (missing; the provider is told);
  * a provider that offers a subject of the test but submitted no usable paper for it is told; no other provider's or teacher's paper is
    ever used instead;
  * students with the same set of papers form one group, and each group becomes ONE ordinary exam plan (audience: those students,
    slots: those exact paper versions, marking and duration of the test), generated by the normal generator - so delivery, the
    "new test" notifications, attempts, the timer, evaluation and results are the existing ones.

Idempotent: a group's plan is keyed by (occurrence, provider, paper set) through exam_plans.client_request_id and the generator is
idempotent per plan, so a retried or concurrent run creates nothing twice; the occurrence is marked generated only when every provider
succeeded. Generated exams never change afterwards (late submissions are refused at the deadline)."""
import hashlib
from collections import defaultdict
from datetime import datetime, timedelta
from uuid import UUID

from sqlalchemy import select
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from institute_common.core import audit
from institute_common.core.roles import Role
from institute_common.database import utcnow
from institute_common.models.academics import ProviderSubject, Subject
from institute_common.models.exams import (
    ExamPlan, ExamPlanStudent, ExamPlanSubject, GlobalPaperSubmission, GlobalTest, GlobalTestOccurrence, GlobalTestSubject,
)
from institute_common.models.papers import PaperVersion
from institute_common.models.staff import StaffRoleAssignment
from inst_exam.services import exam_generation as gen
from inst_exam.services.notify import notify

READY = {"APPROVED", "PUBLISHED"}


def deadline(test: GlobalTest, occ: GlobalTestOccurrence) -> datetime:
    """Papers are accepted (and withdrawn) until this moment; then the occurrence is generated."""
    return occ.start_at - timedelta(minutes=test.generate_lead_minutes)


def resolve_submission(db: Session, sub: GlobalPaperSubmission) -> list[tuple[str, str, UUID | None]]:
    from inst_exam.routes.tests import TestAudienceIn, resolve
    return resolve(db, TestAudienceIn.model_validate(sub.audience))


def assignments(db: Session, occ: GlobalTestOccurrence, provider_id: UUID) -> dict:
    """Who gets which paper for one provider: {"papers": {student: {subject: (submission, enrollment_id)}}, "ambiguous": {(student,
    subject)}, "not_ready": [submission]}. Pure computation, writes nothing (also used for coverage before the deadline)."""
    subs = db.scalars(select(GlobalPaperSubmission).where(GlobalPaperSubmission.occurrence_id == occ.occurrence_id,
                                                          GlobalPaperSubmission.provider_id == provider_id,
                                                          GlobalPaperSubmission.status == "ACTIVE")
                      .order_by(GlobalPaperSubmission.submitted_at)).all()
    papers: dict[str, dict[UUID, tuple[GlobalPaperSubmission, str]]] = defaultdict(dict)
    ambiguous: set[tuple[str, UUID]] = set()
    not_ready = []
    for sub in subs:
        v = db.get(PaperVersion, sub.paper_version_id)
        if not v or v.status not in READY:
            not_ready.append(sub)
            continue
        for sid, eid, _bid in resolve_submission(db, sub):
            if sub.subject_id in papers[sid] and papers[sid][sub.subject_id][0].submission_id != sub.submission_id:
                ambiguous.add((sid, sub.subject_id))
            else:
                papers[sid][sub.subject_id] = (sub, eid)
    for sid, subject in ambiguous:
        papers[sid].pop(subject, None)
    return {"papers": {sid: m for sid, m in papers.items() if m}, "ambiguous": ambiguous, "not_ready": not_ready}


def _provider_admins(db: Session, provider_id: UUID) -> list[UUID]:
    return list(db.scalars(select(StaffRoleAssignment.staff_id).where(StaffRoleAssignment.provider_id == provider_id,
                                                                      StaffRoleAssignment.role == Role.PROVIDER_ADMIN.value,
                                                                      StaffRoleAssignment.status == "ACTIVE")))


def _uncovered(db: Session, provider_id: UUID, covered: set[str]) -> dict[str, int]:
    """Active students of the provider that no submission covers, counted per branch name (who did not get the test at all)."""
    from institute_common.models.org import Branch, Enrollment
    out: dict[str, int] = defaultdict(int)
    seen = set()
    for sid, branch in db.execute(select(Enrollment.student_id, Branch.name).join(Branch, Branch.branch_id == Enrollment.branch_id)
                                  .where(Enrollment.provider_id == provider_id, Enrollment.status == "ACTIVE")):
        if sid not in covered and sid not in seen:
            seen.add(sid)
            out[branch] += 1
    return dict(out)


def _group_key(occ: GlobalTestOccurrence, provider_id: UUID, paper_set: tuple) -> str:
    digest = hashlib.sha256(repr(paper_set).encode()).hexdigest()[:24]
    return f"gocc:{occ.occurrence_id.hex[:20]}:{provider_id.hex[:12]}:{digest}"[:100]


def _plan_for_group(db: Session, test: GlobalTest, occ: GlobalTestOccurrence, provider_id: UUID, subject_order: list[UUID],
                    paper_set: tuple, students: list[tuple[str, str]], home_branch: UUID) -> ExamPlan:
    key = _group_key(occ, provider_id, paper_set)
    plan = db.scalar(select(ExamPlan).where(ExamPlan.client_request_id == key))
    if plan:
        return plan
    plan = ExamPlan(provider_id=provider_id, branch_id=home_branch, name=test.name, description=test.description,
                    duration_minutes=test.duration_minutes, start_at=occ.start_at, end_at=occ.end_at, auto_publish=True, status="ACTIVE",
                    audience_type="STUDENTS", marking_mode=test.marking_mode, marks_correct=test.marks_correct, marks_wrong=test.marks_wrong,
                    exam_type=test.exam_type, target_class=test.target_class, global_test_id=test.test_id,
                    global_occurrence_id=occ.occurrence_id, client_request_id=key, created_by=test.created_by)
    db.add(plan)
    try:
        db.flush()
        for sid, _eid in students:
            db.add(ExamPlanStudent(plan_id=plan.plan_id, student_id=sid))
        versions = dict(paper_set)
        for pos, subject in enumerate([s for s in subject_order if s in versions], start=1):
            db.add(ExamPlanSubject(plan_id=plan.plan_id, position=pos, subject_id=subject, paper_version_id=versions[subject]))
        db.commit()
    except IntegrityError:          # a concurrent run created this group's plan first
        db.rollback()
        plan = db.scalar(select(ExamPlan).where(ExamPlan.client_request_id == key))
    return plan


def generate_occurrence(db: Session, occ: GlobalTestOccurrence, now: datetime | None = None) -> dict:
    """Generate every provider's exams for one occurrence (see module docstring). Returns a report."""
    now = now or utcnow()
    test = db.get(GlobalTest, occ.test_id)
    subject_order = [s for (s,) in db.execute(select(GlobalTestSubject.subject_id).where(GlobalTestSubject.test_id == test.test_id)
                                              .order_by(GlobalTestSubject.position))]
    names = dict(db.execute(select(Subject.subject_id, Subject.name).where(Subject.subject_id.in_(subject_order or [None]))).all())
    providers = sorted({p for (p,) in db.execute(select(GlobalPaperSubmission.provider_id).where(
        GlobalPaperSubmission.occurrence_id == occ.occurrence_id, GlobalPaperSubmission.status == "ACTIVE"))}, key=str)
    offering = sorted({p for (p,) in db.execute(select(ProviderSubject.provider_id).where(ProviderSubject.subject_id.in_(subject_order or [None])))}, key=str)
    report = {"plans": 0, "exams": [], "students": 0, "ambiguous": 0, "missing": [], "failed": []}
    when = occ.start_at.strftime("%d %b %Y %H:%M UTC")
    for provider_id in providers:
        try:
            a = assignments(db, occ, provider_id)
            groups: dict[tuple, list[tuple[str, str]]] = defaultdict(list)
            homes: dict[tuple, UUID] = {}
            for sid, per_subject in sorted(a["papers"].items()):
                paper_set = tuple(sorted((subject, sub.paper_version_id) for subject, (sub, _eid) in per_subject.items()))
                groups[paper_set].append((sid, next(iter(per_subject.values()))[1]))
                homes.setdefault(paper_set, next(iter(per_subject.values()))[0].branch_id)
            for paper_set, students in groups.items():
                plan = _plan_for_group(db, test, occ, provider_id, subject_order, paper_set, students, homes[paper_set])
                job = gen.generate(db, plan.plan_id)
                report["plans"] += 1
                report["students"] += len(students)
                if job.exam_id:
                    report["exams"].append(str(job.exam_id))
            # what this provider is missing: tell its admins (and never fill the gap with someone else's paper)
            covered = {subject for per in a["papers"].values() for subject in per}
            offered = {s for (s,) in db.execute(select(ProviderSubject.subject_id).where(ProviderSubject.provider_id == provider_id,
                                                                                       ProviderSubject.subject_id.in_(subject_order)))}
            partial = defaultdict(int)
            for per in a["papers"].values():
                for subject in offered - set(per):
                    partial[subject] += 1
            problems = [f"{names.get(s, 'A subject')}: no usable paper was submitted" for s in offered - covered]
            problems += [f"{names.get(s, 'A subject')}: {n} student(s) are not covered by any submission and sit the test without it"
                         for s, n in partial.items() if s in covered]
            problems += [f"A {names.get(sub.subject_id, 'subject')} paper was not approved by the deadline and was not used" for sub in a["not_ready"]]
            uncovered = _uncovered(db, provider_id, set(a["papers"]) | {sid for sid, _s in a["ambiguous"]})
            if uncovered:
                problems.append(f"{sum(uncovered.values())} active student(s) are covered by no paper and were not assigned this test "
                                f"({', '.join(f'{b}: {n}' for b, n in sorted(uncovered.items()))})")
            if a["ambiguous"]:
                problems.append(f"{len(a['ambiguous'])} student/subject pair(s) were covered by two submissions and received neither paper")
                report["ambiguous"] += len(a["ambiguous"])
            if problems:
                report["missing"].append({"provider_id": str(provider_id), "problems": problems})
                notify(db, _provider_admins(db, provider_id), kind="GLOBAL_TEST_MISSING_PAPERS", title=f"{test.name} ({when}): papers missing",
                       body="The Global Test was generated for your students with these gaps:\n- " + "\n- ".join(problems),
                       dedupe=f"gmiss:{occ.occurrence_id}:{provider_id}", provider_id=provider_id)
        except Exception as exc:  # recorded and retried on the next pass; other providers continue
            db.rollback()
            report["failed"].append({"provider_id": str(provider_id), "error": f"{type(exc).__name__}: {str(exc)[:200]}"})
    # providers that offer a subject of the test and submitted nothing at all
    for provider_id in offering:
        if provider_id not in providers:
            notify(db, _provider_admins(db, provider_id), kind="GLOBAL_TEST_MISSING_PAPERS", title=f"{test.name} ({when}): no papers submitted",
                   body="No paper was submitted for this Global Test, so none of your students were assigned it.",
                   dedupe=f"gmiss:{occ.occurrence_id}:{provider_id}", provider_id=provider_id)
    occ = db.get(GlobalTestOccurrence, occ.occurrence_id)
    if report["failed"]:
        occ.generation_error = "; ".join(f["error"] for f in report["failed"])[:1000]
    else:
        occ.generated_at, occ.generation_error = now, None
    db.commit()
    audit.record(db, "global_test.occurrence.generate", "FAILURE" if report["failed"] else "SUCCESS", service="exam-scheduler",
                 target_type="global_test_occurrence", target_id=occ.occurrence_id,
                 details={k: (v if k != "exams" else len(v)) for k, v in report.items()})
    return report


def run_due(db: Session, now: datetime | None = None) -> list[dict]:
    """Worker entry point: generate every published occurrence whose submission deadline has passed and that is not generated yet."""
    now = now or utcnow()
    out = []
    rows = db.execute(select(GlobalTestOccurrence, GlobalTest).join(GlobalTest, GlobalTest.test_id == GlobalTestOccurrence.test_id)
                      .where(GlobalTestOccurrence.status == "PUBLISHED", GlobalTestOccurrence.generated_at.is_(None),
                             GlobalTest.status == "PUBLISHED", GlobalTest.kind == "SCHEDULE")).all()
    for occ, test in rows:
        if deadline(test, occ) <= now:
            out.append({"occurrence_id": str(occ.occurrence_id), **generate_occurrence(db, occ, now)})
    return out

"""Object storage for private files (question pictures first): one small interface, two implementations.

    LocalObjectStore  files in a private directory (development, tests, single-server deployments)
    S3ObjectStore     an S3-compatible bucket: AWS S3 today; Cloudflare R2 (or MinIO) later by setting OBJECT_STORE_ENDPOINT_URL

Business code only ever calls `get_object_store()` and the five methods of `ObjectStore`, so switching provider is configuration, not
code. Which one is used comes from the environment (institute_common.config):

    OBJECT_STORE=local|s3              default local
    OBJECT_STORE_DIR                   local only: the private directory (default ./var/objects)
    OBJECT_STORE_BUCKET                s3 only: the bucket (must be PRIVATE: Block Public Access on)
    OBJECT_STORE_REGION                s3 only, e.g. ap-south-1
    OBJECT_STORE_ENDPOINT_URL          s3 only, optional: an S3-compatible endpoint (R2, MinIO); empty for AWS
    OBJECT_STORE_PREFIX                optional prefix inside the bucket/directory, e.g. "prod/"
    OBJECT_STORE_SIGNED_URL_SECONDS    lifetime of a signed download URL (default 300)

Credentials are NEVER settings of this application: the S3 client uses the standard AWS credential chain (AWS_ACCESS_KEY_ID /
AWS_SECRET_ACCESS_KEY in the environment, a shared credentials file, or an instance/task role). Nothing here logs or returns them.

Security rules:
  * keys are generated by the server (see `question_image_key`), validated against a strict pattern and never taken from users;
  * objects are private: the bucket is never made public; a browser gets bytes only through an authorised API endpoint, which may
    answer with a short-lived signed URL (S3) instead of streaming the bytes itself (local);
  * errors are reported as ObjectStoreError with a generic message; provider error details stay in server logs.
"""
import logging
import re
import shutil
from pathlib import Path
from typing import Protocol
from uuid import UUID

from institute_common.config import settings

log = logging.getLogger("institute.objectstore")

# lowercase letters, digits and . _ - / only; no leading slash, no "..", at most 300 characters (the storage_key column)
KEY_PATTERN = re.compile(r"^(?!/)(?!.*\.\.)[a-z0-9][a-z0-9._/-]{0,299}$")


class ObjectStoreError(Exception):
    """The store could not complete the request. The message is safe to show; the cause is logged, never returned."""


class ObjectMissing(ObjectStoreError):
    """No object has this key."""


def check_key(key: str) -> str:
    """The key if it is a server-made key of the expected shape; ValueError otherwise (defence in depth against path tricks)."""
    if not isinstance(key, str) or not KEY_PATTERN.match(key):
        raise ValueError("invalid object key")
    return key


def question_image_key(provider_id: UUID | None, checksum: str) -> str:
    """Where one provider's question picture lives: question-images/<provider>/<sha256>; a platform picture (provider_id None, GLOBAL
    imports): question-images/platform/<sha256>. The same picture of the same owner always has the same key, so storing it twice is
    harmless (it is deduplicated like question_image_assets)."""
    if not re.fullmatch(r"[0-9a-f]{64}", checksum):
        raise ValueError("checksum must be a lowercase SHA-256 hex digest")
    return check_key(f"question-images/{provider_id or 'platform'}/{checksum}")


class ObjectStore(Protocol):
    """What business code may do with stored objects. Every method takes a server-made key (check_key)."""

    name: str      # stored in the database next to each key ("local" | "s3"), so a later provider change never loses track of old objects

    def put(self, key: str, data: bytes, content_type: str) -> None: ...
    def put_file(self, key: str, path: str, content_type: str) -> None: ...   # large files: streamed from disk, never all in memory
    def get(self, key: str) -> bytes: ...                 # raises ObjectMissing
    def download(self, key: str, path: str) -> None: ...  # large files: streamed to disk; raises ObjectMissing
    def delete(self, key: str) -> bool: ...               # False when already gone; deleting twice is safe
    def exists(self, key: str) -> bool: ...
    def signed_url(self, key: str, content_type: str) -> str | None: ...   # None: this store cannot sign; stream the bytes instead


# ------------------------------------------------------------------ local directory

class LocalObjectStore:
    """Objects as files under one private directory (0700 directories, 0600 files). Keys map to paths below the root only."""

    name = "local"

    def __init__(self, root: str | None = None, prefix: str | None = None) -> None:
        self.root = Path(root or settings.object_store_dir).resolve()
        self.prefix = prefix if prefix is not None else settings.object_store_prefix

    def _path(self, key: str) -> Path:
        path = (self.root / (self.prefix + check_key(key))).resolve()
        if self.root not in path.parents:              # never outside the root, whatever the key contains
            raise ValueError("invalid object key")
        return path

    def put(self, key: str, data: bytes, content_type: str) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        tmp = path.with_name(path.name + ".partial")    # write then rename: a reader never sees half a file
        tmp.write_bytes(data)
        tmp.chmod(0o600)
        tmp.replace(path)

    def put_file(self, key: str, path: str, content_type: str) -> None:
        target = self._path(key)
        target.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        tmp = target.with_name(target.name + ".partial")
        shutil.copyfile(path, tmp)                        # copies in chunks
        tmp.chmod(0o600)
        tmp.replace(target)

    def get(self, key: str) -> bytes:
        try:
            return self._path(key).read_bytes()
        except FileNotFoundError:
            raise ObjectMissing("The stored file is missing.") from None

    def download(self, key: str, path: str) -> None:
        try:
            shutil.copyfile(self._path(key), path)
        except FileNotFoundError:
            raise ObjectMissing("The stored file is missing.") from None

    def delete(self, key: str) -> bool:
        try:
            self._path(key).unlink()
            return True
        except FileNotFoundError:
            return False

    def exists(self, key: str) -> bool:
        return self._path(key).is_file()

    def signed_url(self, key: str, content_type: str) -> str | None:
        return None        # a directory cannot sign URLs: the API streams the bytes after its own authorisation check


# ------------------------------------------------------------------ S3-compatible bucket

class S3ObjectStore:
    """Objects in a private S3-compatible bucket. Works with AWS S3, and with Cloudflare R2 / MinIO through `endpoint_url`."""

    name = "s3"

    def __init__(self, bucket: str | None = None, region: str | None = None, endpoint_url: str | None = None,
                 prefix: str | None = None, signed_url_seconds: int | None = None, client=None) -> None:
        self.bucket = bucket or settings.object_store_bucket
        if not self.bucket:
            raise ObjectStoreError("Object storage is not configured (OBJECT_STORE_BUCKET is empty).")
        self.prefix = prefix if prefix is not None else settings.object_store_prefix
        self.signed_url_seconds = signed_url_seconds or settings.object_store_signed_url_seconds
        if client is None:
            import boto3                                    # imported here: only deployments that use S3 need it loaded
            from botocore.config import Config
            client = boto3.client("s3", region_name=region or settings.object_store_region or None,
                                  endpoint_url=endpoint_url or settings.object_store_endpoint_url or None,
                                  config=Config(signature_version="s3v4", retries={"max_attempts": 5, "mode": "standard"}))
        self._client = client

    def _key(self, key: str) -> str:
        return self.prefix + check_key(key)

    def _fail(self, action: str, exc: Exception) -> ObjectStoreError:
        log.warning("object store %s failed: %s", action, type(exc).__name__)     # never the request, keys or credentials
        return ObjectStoreError("The file store is unavailable. Try again later.")

    def put(self, key: str, data: bytes, content_type: str) -> None:
        # Encryption at rest: S3 encrypts every new object (SSE-S3) by default; no extra header, so R2 (which rejects it) also works.
        try:
            self._client.put_object(Bucket=self.bucket, Key=self._key(key), Body=data, ContentType=content_type)
        except Exception as exc:
            raise self._fail("put", exc) from exc

    def put_file(self, key: str, path: str, content_type: str) -> None:
        try:      # upload_file streams the file in parts (multipart for large files)
            self._client.upload_file(path, self.bucket, self._key(key), ExtraArgs={"ContentType": content_type})
        except Exception as exc:
            raise self._fail("put", exc) from exc

    def download(self, key: str, path: str) -> None:
        try:
            self._client.download_file(self.bucket, self._key(key), path)
        except Exception as exc:
            if _is_missing(exc):
                raise ObjectMissing("The stored file is missing.") from None
            raise self._fail("download", exc) from exc

    def get(self, key: str) -> bytes:
        try:
            return self._client.get_object(Bucket=self.bucket, Key=self._key(key))["Body"].read()
        except Exception as exc:
            if _is_missing(exc):
                raise ObjectMissing("The stored file is missing.") from None
            raise self._fail("get", exc) from exc

    def delete(self, key: str) -> bool:
        existed = self.exists(key)
        try:
            self._client.delete_object(Bucket=self.bucket, Key=self._key(key))     # S3 delete is idempotent
        except Exception as exc:
            raise self._fail("delete", exc) from exc
        return existed

    def exists(self, key: str) -> bool:
        try:
            self._client.head_object(Bucket=self.bucket, Key=self._key(key))
            return True
        except Exception as exc:
            if _is_missing(exc):
                return False
            raise self._fail("head", exc) from exc

    def signed_url(self, key: str, content_type: str) -> str:
        """A GET URL valid for `signed_url_seconds` that serves the object with its own content type and as inline content."""
        try:
            return self._client.generate_presigned_url(
                "get_object", ExpiresIn=self.signed_url_seconds,
                Params={"Bucket": self.bucket, "Key": self._key(key), "ResponseContentType": content_type,
                        "ResponseContentDisposition": "inline", "ResponseCacheControl": "private, no-store"})
        except Exception as exc:
            raise self._fail("sign", exc) from exc


def _is_missing(exc: Exception) -> bool:
    """True for "no such key" answers of S3-compatible services (404 / NoSuchKey / NotFound)."""
    response = getattr(exc, "response", None) or {}
    code = str(response.get("Error", {}).get("Code", ""))
    status = response.get("ResponseMetadata", {}).get("HTTPStatusCode")
    return code in ("NoSuchKey", "404", "NotFound") or status == 404


# ------------------------------------------------------------------ the configured store

_store: ObjectStore | None = None


def get_object_store() -> ObjectStore:
    """The store selected by OBJECT_STORE (created once per process)."""
    global _store
    if _store is None:
        if settings.object_store == "s3":
            _store = S3ObjectStore()
        elif settings.object_store == "local":
            _store = LocalObjectStore()
        else:
            raise ObjectStoreError("OBJECT_STORE must be 'local' or 's3'.")
    return _store


def store_named(name: str) -> ObjectStore:
    """The store that holds objects recorded with storage `name`. Today one process uses one store; an object written by another
    kind (e.g. 'local' after switching to 's3') is reported as unavailable rather than read from the wrong place."""
    store = get_object_store()
    if store.name != name:
        raise ObjectStoreError(f"This file is kept in '{name}' storage, which this service is not configured to read.")
    return store


def stored_asset_bytes(asset) -> bytes:
    """The bytes of a question picture (question_image_assets row) wherever `asset.storage` says they live. ObjectStoreError
    (ObjectMissing included) when they cannot be read. Shared by the paper service (staff image endpoint) and the exam service
    (delivery of pictures to the Student test service)."""
    if asset.storage == "db":
        if asset.image_data is None:
            raise ObjectMissing("The stored picture is missing.")
        return asset.image_data
    return store_named(asset.storage).get(asset.storage_key)


def set_object_store(store: ObjectStore | None) -> None:
    """Tests: use `store` (None: back to configuration)."""
    global _store
    _store = store
